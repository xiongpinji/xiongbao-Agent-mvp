CREATE OR REPLACE FUNCTION project_todo_attachment_retain_before_delete()
RETURNS trigger LANGUAGE plpgsql AS $d1$
BEGIN
  IF EXISTS (
    SELECT 1 FROM project_todo_attachment_retained_objects r WHERE r.object_key = OLD.object_key
      AND ROW(r.attachment_id, r.project_id, r.todo_id, r.uploader_user_id, r.display_name,
        r.size_bytes, r.sha256, r.preview_media_type, r.preview_width, r.preview_height,
        r.created_at, r.removed_at, r.client_request_id, r.request_fingerprint)
      IS DISTINCT FROM ROW(OLD.attachment_id, OLD.project_id, OLD.todo_id,
        OLD.uploader_user_id, OLD.display_name, OLD.size_bytes, OLD.sha256,
        OLD.preview_media_type, OLD.preview_width, OLD.preview_height,
        OLD.created_at, OLD.removed_at, OLD.client_request_id, OLD.request_fingerprint)
  ) THEN
    RAISE EXCEPTION 'todo_attachment_retained_conflict' USING ERRCODE = '23514';
  END IF;
  INSERT INTO project_todo_attachment_retained_objects (
    object_key, attachment_id, project_id, todo_id, uploader_user_id, display_name,
    size_bytes, sha256, preview_media_type, preview_width, preview_height,
    created_at, removed_at, client_request_id, request_fingerprint, retained_at
  ) VALUES (
    OLD.object_key, OLD.attachment_id, OLD.project_id, OLD.todo_id, OLD.uploader_user_id, OLD.display_name,
    OLD.size_bytes, OLD.sha256, OLD.preview_media_type, OLD.preview_width, OLD.preview_height,
    OLD.created_at, OLD.removed_at, OLD.client_request_id, OLD.request_fingerprint,
    floor(extract(epoch FROM statement_timestamp()))::BIGINT
  ) ON CONFLICT(object_key) DO NOTHING;
  RETURN OLD;
END;
$d1$;

-- D1_STATEMENT_BOUNDARY

CREATE TRIGGER trg_project_todo_attachment_retain_before_delete
BEFORE DELETE ON project_todo_attachments
FOR EACH ROW EXECUTE FUNCTION project_todo_attachment_retain_before_delete();

