CREATE OR REPLACE FUNCTION users_todo_display_before_delete()
RETURNS trigger LANGUAGE plpgsql AS $d1$
DECLARE
  target record;
  changed INTEGER;
BEGIN
  FOR target IN
    SELECT t.project_id, t.todo_id FROM project_todos t
    WHERE t.assignee_user_id = OLD.id AND t.creator_user_id <> OLD.id
    ORDER BY t.project_id, t.todo_id FOR UPDATE OF t
  LOOP
    UPDATE project_todo_display_state
      SET revision = revision + 1,
          updated_at = floor(extract(epoch FROM statement_timestamp()))::BIGINT
      WHERE project_id = target.project_id AND todo_id = target.todo_id
        AND revision < 9007199254740991;
    GET DIAGNOSTICS changed = ROW_COUNT;
    IF changed <> 1 THEN
      RAISE EXCEPTION 'todo_display_state_missing_or_exhausted' USING ERRCODE = '23514';
    END IF;
  END LOOP;
  RETURN OLD;
END;
$d1$;

